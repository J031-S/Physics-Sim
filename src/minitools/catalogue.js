const deg = Math.PI / 180;
const V = (key, latex, name, unit, min, max, value, scale = "linear") => ({
  key,
  latex,
  name,
  unit,
  min,
  max,
  value,
  scale,
});
const K = (key, latex, name, value, unit) => ({
  key,
  latex,
  name,
  value,
  unit,
});
const tool = (entry) => ({
  kind: "single",
  constants: [],
  derivation: [],
  uses: [],
  visual: "graph",
  wants: null,
  related: null,
  verified: false,
  ...entry,
  // The mini simulation, if this tool has one (sims.js).
  sim: sims[entry.id] ?? null,
  // Where the equation comes from, a note under the purpose, and a check
  // that the values are ones the equation describes (explain.js).
  derivation: (explain[entry.id]?.origin ?? []).map(([say, latex]) => ({
    say,
    latex,
  })),
  // A longer description for the top of the page, and the idea behind the
  // derivation in a sentence or two.
  about: explain[entry.id]?.about ?? null,
  idea: explain[entry.id]?.idea ?? null,
  note: explain[entry.id]?.note ?? null,
  check: explain[entry.id]?.check ?? null,
  // Asymptotes just beyond a slider's range, for the graph (v = c).
  asymptotes: explain[entry.id]?.asymptotes ?? [],
});

