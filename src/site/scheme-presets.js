// Built-in developer schemes: ready-made themes for the whole site, offered
// beside the schemes the author saves. Picking one loads a copy as the
// working scheme, which can then be changed and saved under a new name; the
// built-in itself never changes. No DOM. Every one is checked by
// checkScheme and for readable contrast in tests/developer.test.mjs.
//
// Each scheme sets the page colours of both themes. Most keep the physics
// colours of theme.js (velocity blue, force orange, + red, − blue), so that
// a picture means the same in every scheme; those that change them say why.

// The eleven colours that make up the surfaces, text and accent.
const surface = (s) => ({
  "canvas-bg": s.bg,
  panel: s.panel,
  line: s.line,
  ink: s.ink,
  "ink-soft": s.soft,
  accent: s.accent,
  "accent-text": s.accentText,
  "accent-soft": s.accentSoft,
  shadow: s.shadow,
  "canvas-grid": s.grid,
  "canvas-ground": s.ground,
  ...(s.structure ? { structure: s.structure } : {}),
});

const scheme = (name, light, dark, values = {}, css = "") => ({
  physiumScheme: 1,
  name,
  light,
  dark,
  values,
  css,
});

